"""Generate the kernel checks of `Prelim/SmallMstar.lean`: `S(k) log(k+1) ≤ 0.8` for `1 ≤ k ≤ 22026`,
where `S(k) = ∑_{w ≤ √k} |m(k/w²)|/w²` and `m(y) = ∑_{n ≤ y} μ(n)/n` (for [H, (2.22)] with `4/5`).

* The table: `t_j = ⌈10¹² |m(j)|⌉` (from the interval bounds of `SmallMcheck`'s walk) for
  `j ≤ 22027`, 64 entries of 40 bits per block, the blocks at the leaves of a binary tree of depth 9
  (`SmallMstarTable.lean`). A single big number would be simpler, but every lookup into it leaves a
  large intermediate in the kernel's cache.
* The table walk (`twalk`): `SmallMcheck.step`, checking `max(−mlo, mhi) ≤ 10⁸ t_k` at each `k`.
* The `S` walk (`swalk`): `S(k)` is kept in the state and updated incrementally: from `k` to `k + 1`
  only the terms with `w² ∣ k + 1` change (and a new term appears when `k + 1` is a square), so a step
  costs a scan of `w ≤ √k` and a few lookups. It checks `S·L ≤ 0.8 · 10³²`, where `S ≥ 10¹² S(k)` and
  `L ≥ 10²⁰ log(k+1)` (`SmallMcheck.logHi`).

Both walks are mirrored exactly here, in Python integers.

Usage: python3 scripts/gen_mstar_small.py [--write]
"""
import math, os, sys

sys.set_int_max_str_digits(0)
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen_mcheck_small as G  # noqa: E402

K = 22026                 # ⌊e¹⁰⌋
BLK, DEPTH, W = 64, 9, 40  # entries per block, tree depth, bits per entry
TCHUNK, TPER = 2000, 6    # table walk: steps per chunk, chunks per file
SCHUNK, SPER = 1000, 4    # S walk: steps per chunk, chunks per file
BOUND = 8 * 10 ** 31      # 0.8 · 10¹² · 10²⁰
NS = "TernaryGoldbach.Prelim.SmallMstar"
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "TernaryGoldbach", "Prelim")


def table():
    mu = G.mu_table(K + 3)
    s = (1, 1, G.B, G.B, 0, 0, 0)
    t = [0] * (K + 2)
    tstates = [s]
    for k in range(1, K + 2):
        assert s[0] == k
        t[k] = -((-max(-s[2], s[3])) // 10 ** 8)
        assert t[k] < 2 ** W and max(-s[2], s[3]) <= t[k] * 10 ** 8
        s = G.step(s, mu)
        if k % TCHUNK == 0 or k == K + 1:
            tstates.append(s)
    return t, tstates


def walk_S(t):
    def c(k, w):
        return (t[k // (w * w)] + w * w - 1) // (w * w)
    k, r = 1, 1
    S, L = c(1, 1), G.log_hi(1)
    states = [(k, r, S, L)]
    worst = (0, 0)
    while k <= K:
        assert S * L <= BOUND, (k, S * L / 10 ** 32)
        worst = max(worst, (S * L / 10 ** 32, k))
        r2 = r + 1 if (r + 1) * (r + 1) == k + 1 else r
        d = sum(c(k + 1, w) - c(k, w) for w in range(1, r + 1) if (k + 1) % (w * w) == 0)
        S = S + d + (0 if r2 == r else c(k + 1, r2))
        L = L + G.log_hi(k + 1)
        k, r = k + 1, r2
        if (k - 1) % SCHUNK == 0 or k == K + 1:
            states.append((k, r, S, L))
    # spot-check the incremental S against the direct sum
    for kk, rr, SS, _ in states:
        assert rr == math.isqrt(kk) and SS == sum(c(kk, w) for w in range(1, rr + 1))
    return states, worst


def lean_int(z):
    return f"({z})" if z < 0 else str(z)


def st(s):
    return "⟨" + ", ".join(lean_int(z) for z in s) + "⟩"


def tree_src(t):
    nb = (K + 2 + BLK - 1) // BLK
    blocks = []
    for i in range(nb):
        v = 0
        for r in range(BLK):
            j = BLK * i + r
            if j <= K + 1:
                v |= t[j] << (W * r)
        blocks.append(v)
    blocks += [0] * (2 ** DEPTH - nb)

    def go(lo, hi):
        if hi - lo == 1:
            return f"(.lf {blocks[lo]})"
        mid = (lo + hi) // 2
        return f"(.nd {go(lo, mid)} {go(mid, hi)})"
    return go(0, 2 ** DEPTH)


def write(t, tstates, sstates):
    with open(os.path.join(ROOT, "SmallMstarTable.lean"), "w") as f:
        f.write(f"""/-!
Generated by `scripts/gen_mstar_small.py`: `t_j = ⌈10¹² |m(j)|⌉` for `j ≤ {K + 1}` (from the interval bounds
of `SmallMcheck`'s walk; checked in `SmallMstar.lean`), {BLK} entries of {W} bits per block, the blocks
at the leaves of a binary tree of depth {DEPTH}.
-/

namespace {NS}

/-- A binary tree with numbers at the leaves. -/
inductive Tbl
  | lf (v : Nat)
  | nd (l r : Tbl)

/-- The leaf reached by the low `d` bits of `i`, most significant first. -/
def Tbl.get : Tbl → Nat → Nat → Nat
  | .lf v, _, _ => v
  | .nd l r, d + 1, i => cond (Nat.beq ((i >>> d) % 2) 0) (l.get d i) (r.get d i)
  | .nd _ _, 0, _ => 0

/-- The table. -/
def tree : Tbl := {tree_src(t)}

/-- `t_j`. -/
def tget (j : Nat) : Nat := ((tree.get {DEPTH} (j / {BLK})) >>> ({W} * (j % {BLK}))) % {2 ** W}

end {NS}
""")
    tchunks = list(zip(tstates, tstates[1:]))
    schunks = list(zip(sstates, sstates[1:]))
    tfiles = [tchunks[i:i + TPER] for i in range(0, len(tchunks), TPER)]
    sfiles = [schunks[i:i + SPER] for i in range(0, len(schunks), SPER)]
    names = []
    idx = 0
    for fi, group in enumerate(tfiles):
        name = f"SmallMstarTData{fi + 1}"
        names.append(name)
        lines = ["import TernaryGoldbach.Prelim.SmallMstar", "",
                 "/-! Generated by `scripts/gen_mstar_small.py`: chunks of the table walk of `SmallMstar.lean`. -/",
                 "", f"namespace {NS}", ""]
        for a, b in group:
            lines += [f"theorem tchunk_{idx} : twalk {b[0] - a[0]} {st(a)} =",
                      f"    some {st(b)} := by", "  decide +kernel", ""]
            idx += 1
        lines.append(f"end {NS}")
        open(os.path.join(ROOT, name + ".lean"), "w").write("\n".join(lines) + "\n")
    idx = 0
    for fi, group in enumerate(sfiles):
        name = f"SmallMstarSData{fi + 1}"
        names.append(name)
        lines = ["import TernaryGoldbach.Prelim.SmallMstar", "",
                 "/-! Generated by `scripts/gen_mstar_small.py`: chunks of the `S` walk of `SmallMstar.lean`. -/",
                 "", f"namespace {NS}", ""]
        for a, b in group:
            lines += [f"theorem schunk_{idx} : swalk {b[0] - a[0]} {st(a)} =",
                      f"    some {st(b)} := by", "  decide +kernel", ""]
            idx += 1
        lines.append(f"end {NS}")
        open(os.path.join(ROOT, name + ".lean"), "w").write("\n".join(lines) + "\n")
    # the chain
    body = [f"import TernaryGoldbach.Prelim.{n}" for n in names] + [
        "", "/-! Generated by `scripts/gen_mstar_small.py`: the chunks of `SmallMstarTData*.lean` and",
        "`SmallMstarSData*.lean`, chained. -/", "", f"namespace {NS}", "",
        f"theorem table_all : ∀ j : ℕ, 1 ≤ j → j ≤ {K + 1} → (10 ^ 12 : ℝ) * |msumR (j : ℝ)| ≤ tget j := by",
        "  have h0 := tgood_init"]
    for i in range(len(tchunks)):
        body.append(f"  have h{i + 1} := tchain h{i}.1 h{i}.2 tchunk_{i}")
    body += [f"  exact fun j h1 h2 => h{len(tchunks)}.2 j h1 (by show j < {tstates[-1][0]}; omega)", "",
             f"theorem walk_all : ∀ k : ℕ, 1 ≤ k → k ≤ {K} → Sm (k : ℝ) * Real.log (k + 1) ≤ 0.8 := by",
             "  have h0 := sgood_init"]
    for i in range(len(schunks)):
        body.append(f"  have h{i + 1} := schain table_all h{i}.1 h{i}.2 schunk_{i} (by decide)")
    body += [f"  exact fun k h1 h2 => h{len(schunks)}.2 k h1 (by show k < {sstates[-1][0]}; omega)", "",
             f"end {NS}"]
    open(os.path.join(ROOT, "SmallMstarMain.lean"), "w").write("\n".join(body) + "\n")
    print(f"wrote SmallMstarTable.lean, {len(tfiles)} table files, {len(sfiles)} S files, SmallMstarMain.lean")
    print(f"tstates[0] = {st(tstates[0])}, sstates[0] = {st(sstates[0])}")


def main():
    t, tstates = table()
    sstates, worst = walk_S(t)
    print(f"max S(k) log(k+1) over 1 ≤ k ≤ {K} (as checked): {worst[0]:.6f} at k = {worst[1]}")
    print(f"table walk: {len(tstates) - 1} chunks to k = {tstates[-1][0]}; S walk: {len(sstates) - 1} chunks to k = {sstates[-1][0]}")
    if "--write" in sys.argv:
        write(t, tstates, sstates)


if __name__ == "__main__":
    main()
