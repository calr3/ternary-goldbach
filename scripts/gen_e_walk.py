"""Data for Prelim/SmallEData*.lean and Prelim/SmallEMain.lean: the kernel walk of sum_{k<=n} Lambda(k)/k
(Prelim/SmallEWalk.lean) on [1, 10^6], simulated exactly. Chunks of about 2% (single integers below
50, at most 2000 integers); each chunk gets the exact extremes elo, ehi of the checked quantities.

Usage: python3 scripts/gen_e_walk.py"""
import math, sys, os, glob, re
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import io, contextlib
from fractions import Fraction as Q
with contextlib.redirect_stdout(io.StringIO()):
    from cert_tables import ELpow, T12, EHpow, T12up
S = 10**12
TOP = 10**6
def chkStep(cN, cD, n, L):
    a = cN*n//cD; r = cN*n % cD
    return Q(L) < ELpow(a)*T12(Q(r, cD))
def chkLow(cN, cD, L):
    a = cN//cD; r = cN % cD
    return EHpow(a)*T12up(Q(r, cD)) <= L
def logcert(e):
    lo = math.floor(S*math.log(e)) - 2; hi = math.ceil(S*math.log(e)) + 2
    while not chkLow(lo, S, e): lo -= 1
    while not chkStep(hi, S, 1, e): hi += 1
    return lo, hi
# LQ table of SmallPsiTable (scale 1e9)
src = open("TernaryGoldbach/Prelim/SmallPsiTable.lean").read()
m = re.search(r"def LQ : List \(ℕ × ℕ × ℕ\) := \[(.*?)\]\n", src, re.S)
LQ = {int(a): (int(b), int(c)) for a, b, c in re.findall(r"\((\d+), (\d+), (\d+)\)", m.group(1))}
P1000 = sorted(LQ)
def spf(n):
    for p in P1000:
        if n < p*p: return 0
        if n % p == 0: return p
    return 0
def isPowOf(q, k, m):
    for _ in range(k):
        if m == 1: return True
        if m % q != 0: return False
        m //= q
    return False
def cdiv(a, b): return (a + b - 1)//b
def lgLo(n): return S//n - cdiv(S, 2*n**2) + S//(3*n**3) - cdiv(S, 4*n**4) - cdiv(2*S, n**5)
def lgHi(n): return cdiv(S, n) - S//(2*n**2) + cdiv(S, 3*n**3) + cdiv(2*S, n**4)
def lamT(m, lo, hi):
    q = spf(m)
    if q == 0: return lo//m, cdiv(hi, m)
    if isPowOf(q, 20, m): return LQ[q][0]*1000//m, cdiv(LQ[q][1]*1000, m)
    return 0, 0
LOGS = {m: logcert(m) for m in range(2, 1002)}
# walk
st = (0, 0, S, S, 0, 0)   # n = 1
states = {1: st}
chk = {}   # n -> (Lhi - glo, Llo - hi_next)
for n in range(1, TOP):
    Llo, Lhi, Hlo, Hhi, glo, ghi = st
    m = n + 1
    if m <= 1001: lo, hi = LOGS[m]
    else:
        lo = max(0, glo + lgLo(n)); hi = max(0, ghi + lgHi(n))
    chk[n] = (Lhi - glo, Llo - hi)
    a, b = lamT(m, lo, hi)
    st = (Llo + a, Lhi + b, Hlo + S//m, Hhi + cdiv(S, m), lo, hi)
    states[m] = st
# chunks
bnds = [1]
while bnds[-1] < TOP:
    a = bnds[-1]
    ln = 1 if a < 50 else min(2000, max(1, a//50))
    bnds.append(min(TOP, a + ln))
for b in (1001,):
    if b not in bnds: bnds.append(b)
bnds = sorted(set(bnds))
chunks = []
for i in range(len(bnds) - 1):
    a, b = bnds[i], bnds[i+1]
    ehi = max(chk[n][0] for n in range(a, b)); elo = min(chk[n][1] for n in range(a, b))
    logs = [LOGS[m] for m in range(a + 1, b + 1) if m <= 1001]
    chunks.append((a, b, elo, ehi, logs))
print("chunks", len(chunks))
for f in glob.glob("TernaryGoldbach/Prelim/SmallEData*.lean"): os.remove(f)
per_file = 100
HDR = """import {imp}

/-! Data for `Prelim/SmallEWalk.lean` (generated by `scripts/gen_e_walk.py`), part {i}: the walk on
`[{a}, {b})`. -/

namespace TernaryGoldbach.Prelim.SmallE

set_option Elab.async false
"""
def stt(n): return ' '.join(map(str, states[n]))
def sttup(n): return '(' + ', '.join(map(str, states[n])) + ')'
files = []
for f0 in range(0, len(chunks), per_file):
    i = f0//per_file + 1
    imp = "TernaryGoldbach.Prelim.SmallEWalk" if i == 1 else f"TernaryGoldbach.Prelim.SmallEData{i-1}"
    body = [HDR.format(imp=imp, i=i, a=chunks[f0][0], b=chunks[min(f0 + per_file, len(chunks)) - 1][1])]
    for j in range(f0, min(f0 + per_file, len(chunks))):
        a, b, elo, ehi, logs = chunks[j]
        ls = "[" + ", ".join(f"({x}, {y})" for x, y in logs) + "]"
        prevI = "inv_one" if j == 0 else f"i{j-1}"
        body.append(f"set_option maxRecDepth 100000 in\ntheorem w{j} : resEqE (walkE ({elo}) ({ehi}) {a} {sttup(a)} {ls} {b-a}) {stt(b)} = true := by\n  decide +kernel\n")
        body.append(f"theorem k{j} : Inv {b} {stt(b)} ∧ ChunkOK ({a}, {b}, {elo}, {ehi}) :=\n  chunk_step {prevI} w{j}\n")
        body.append(f"theorem i{j} : Inv {b} {stt(b)} := (k{j}).1\n")
        prevT = "[]" if j == 0 else f"T{j-1}"
        body.append(f"def T{j} : List (ℕ × ℕ × ℤ × ℤ) := ({a}, {b}, {elo}, {ehi}) :: {prevT}\n")
        prevOK = "fun _ h => by simp at h" if j == 0 else f"tOK{j-1}"
        body.append(f"theorem tOK{j} : ∀ c ∈ T{j}, ChunkOK c := List.forall_mem_cons.2 ⟨(k{j}).2, {prevOK}⟩\n")
    body.append("end TernaryGoldbach.Prelim.SmallE\n")
    open(f"TernaryGoldbach/Prelim/SmallEData{i}.lean", "w").write("\n".join(body))
    files.append(i)
K = len(chunks) - 1
fin = states[TOP]
main = f"""import TernaryGoldbach.Prelim.SmallEData{files[-1]}

/-!
# A table of `E₁Λ(u) = ∑_{{d ≤ u}} Λ(d)/d − log u` on `[1, 10⁶)` and bounds for `γ`

From the kernel walk of `Prelim/SmallEWalk.lean` (data `Prelim/SmallEData*.lean`, generated by
`scripts/gen_e_walk.py`): `ETab` lists `(a, b, elo, ehi)` with `elo/S ≤ E₁Λ(u) ≤ ehi/S` on `[a, b)`,
`S = 10¹²`, covering `[1, 10⁶)`.
-/

namespace TernaryGoldbach.Prelim.SmallE

/-- The table, in decreasing order of `a`. -/
def ETab : List (ℕ × ℕ × ℤ × ℤ) := T{K}

theorem ETab_ok : ∀ c ∈ ETab, ChunkOK c := tOK{K}

theorem inv_top : Inv {TOP} {stt(TOP)} := i{K}

/-- `{fin[2]}/S − {fin[5]}/S − 10⁻⁶ < γ < {fin[3]}/S − {fin[4]}/S`. -/
theorem gamma_tab : ({fin[2]} : ℝ) / S - ({fin[5]} : ℝ) / S - 1 / {TOP} < Real.eulerMascheroniConstant ∧
    Real.eulerMascheroniConstant < ({fin[3]} : ℝ) / S - ({fin[4]} : ℝ) / S := by
  have := gamma_bounds (N := {TOP}) (by norm_num) inv_top
  push_cast at this
  exact this

end TernaryGoldbach.Prelim.SmallE
"""
open("TernaryGoldbach/Prelim/SmallEMain.lean", "w").write(main)
print("files", len(files), "gamma in", (fin[2]-fin[5])/S - 1e-6, (fin[3]-fin[4])/S)
