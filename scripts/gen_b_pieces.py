"""Generate the piecewise numerical proof of `b_numeric` (SecondTypeIIbPieces.lean).

Every inequality handed to `norm_num` is first checked here in exact rational arithmetic.
"""
from fractions import Fraction as F
from mpmath import mp, mpf, log, sqrt, e as E
mp.dps = 50

def Fd(x): return F(str(x))
def taylor6(f): return 1 + f + f**2/2 + f**3/6 + f**4/24 + f**5/120 + f**6/720
EM = Fd('2.7182818283')

def log_ub(z):
    """(n, f) with log z <= n + f, z <= EM^n taylor6(f), 0 <= f < 1, f with 4 decimals."""
    z = F(z)
    v = log(mpf(z.numerator) / z.denominator)
    n = int(v)
    f = F(int((v - n) * 10000) + 1, 10000)
    while not (z <= EM**n * taylor6(f)):
        f += F(1, 10000)
    if f >= 1:
        n += 1; f -= 1
        while not (z <= EM**n * taylor6(f)):
            f += F(1, 10000)
    assert z <= EM**n * taylor6(f)
    return n, f

def dec(x, places=4, up=True):
    q = F(10**places)
    import math
    v = x * q
    r = math.ceil(v) if up else math.floor(v)
    return F(r, 10**places)

def fstr(x):
    # exact decimal string for a Fraction with power-of-10 denominator
    s = str(float(x))
    assert Fd(s) == x, (x, s)
    return s

c = Fd('9.2355')
pts = ['15.6','17','18.78','21','25','30','40','55']
out = []
names = []
for i, (a, bb) in enumerate(zip(pts, pts[1:])):
    A, B = Fd(a), Fd(bb)
    n1, f1 = log_ub(B - Fd('1.7917')); u1 = n1 + f1
    n2, f2 = log_ub(B - Fd('6.1452')); u2 = n2 + f2
    if A < Fd('18.78'):
        Bexact = Fd('0.15107') / (4 * c)
    else:
        Bexact = Fd('0.15107') * (A - c) / A**2
    Bb = dec(Bexact, 7)
    val = 12 * (Fd('1.7882') * u1 + Fd('0.9549')) * (1 - Fd('9.4778') / B + (1 - Fd('0.9654') / B) * (u2 - Fd('1.2037'))) * Bb
    m = F(int(sqrt(mpf(val.numerator) / val.denominator) * 10**5) + 1, 10**5)
    assert m * m >= val
    sa = F(int(sqrt(mpf(a)) * 10**5), 10**5)
    assert sa * sa <= A
    wv = Fd('0.24083') * (Fd('1.7882') * u1 + Fd('0.9549')) / 2
    w = F(int(sqrt(mpf(wv.numerator) / wv.denominator) * 10**5) + 1, 10**5)
    assert w * w >= wv
    ev = (4 * (Fd('0.49075') * (Fd('0.612373') * (Fd('3.4658') * (1 / A + Fd('1.1836') / A**2)) +
          Fd('0.0019072') * (Fd('1.414214') * (1 - Fd('6.0119') / B)) + Fd('0.70712') * Fd('1.73207') * (1 / A + Fd('1.0373') / A**2) +
          Fd('0.02158') * Fd('1.414214') / A)) +
          8 * Fd('1.4262') * Fd('1.73207') * Fd('0.347013') / (A * sa) +
          4 * w * (Fd('0.057144') / (A * sa) + Fd('0.0848') * (1 / A + Fd('2.3015') / A**2)))
    ee = F(int(ev * 10**5) + 1, 10**5)
    assert ee >= ev
    assert m + ee <= Fd('1.413'), (a, bb, float(m + ee))
    if A < Fd('18.78'):
        hB = """(mul_le_mul_of_nonneg_left (div_sq_le_max (c := 9.2355) (by norm_num) (by linarith))
        (by norm_num)).trans (by norm_num)"""
    else:
        hB = """(mul_le_mul_of_nonneg_left (div_sq_anti (c := 9.2355) (by norm_num) (by norm_num)
        (by norm_num) haL) (by norm_num)).trans (by norm_num)"""
    name = f"b_piece_{i}"
    names.append((a, bb, name))
    out.append(f"""
theorem {name} {{L : ℝ}} (haL : ({a} : ℝ) ≤ L) (hLb : L ≤ {bb}) :
    √(12 * a1F0 L * bX0 L * bB0 L) + bSEC L ≤ 1.413 * (L * √L) := by
  have hm := bM1_piece (a := {a}) (b := {bb}) (u1 := {n1} + {fstr(f1)}) (u2 := {n2} + {fstr(f2)})
    (Bb := {fstr(Bb)}) (m := {fstr(m)}) (by norm_num) haL hLb
    (log_le_num {n1} {fstr(f1)} (by norm_num) (by norm_num) (by norm_num [taylor6]))
    (log_le_num {n2} {fstr(f2)} (by norm_num) (by norm_num) (by norm_num [taylor6]))
    ({hB}) (by norm_num) (by norm_num)
  have he := bE_piece (a := {a}) (b := {bb}) (sa := {fstr(sa)}) (u1 := {n1} + {fstr(f1)})
    (w := {fstr(w)}) (e := {fstr(ee)}) (by norm_num) haL hLb (by norm_num) (by norm_num)
    (log_le_num {n1} {fstr(f1)} (by norm_num) (by norm_num) (by norm_num [taylor6]))
    (by norm_num) (by norm_num) (by norm_num)
  have hs := bSEC_le (show (15.6 : ℝ) ≤ L by linarith)
  have hLL : 0 ≤ L * √L := by positivity
  nlinarith [mul_le_mul_of_nonneg_right he hLL]
""")

header = """import TernaryGoldbach.MinorArcs.SecondTypeIIbNum

/-!
# Case (b): the pieces of `b_numeric` (generated by `scripts/gen_b_pieces.py`)
-/

open Real

namespace TernaryGoldbach.MinorArcs
"""
final = """
theorem b_piece_asym {L : ℝ} (hL : 55 ≤ L) :
    √(12 * a1F0 L * bX0 L * bB0 L) + bSEC L ≤ 1.413 * (L * √L) := by
  have hm := bM1_asym hL
  have he := bE_asym hL
  have hs := bSEC_le (show (15.6 : ℝ) ≤ L by linarith)
  have hLL : 0 ≤ L * √L := by positivity
  nlinarith [mul_le_mul_of_nonneg_right he hLL]

/-- **The numerical inequality of case (b)**: `√(12 F₀X₀ᵇB₀ᵇ) + SECᵇ(L) ≤ 1.413 L^{3/2}`. -/
theorem b_numeric {L : ℝ} (hL : 15.6 ≤ L) :
    √(12 * a1F0 L * bX0 L * bB0 L) + bSEC L ≤ 1.413 * (L * √L) := by
"""
lines = []
for (a, bb, name) in names:
    lines.append(f"  rcases le_or_gt L {bb} with h{name} | h{name}\n  · exact {name} (by linarith) h{name}")
lines.append("  exact b_piece_asym (by linarith)")
final += "\n".join(lines) + "\n\nend TernaryGoldbach.MinorArcs\n"
open('/home/charlie/calr3gh/ternary-goldbach/TernaryGoldbach/MinorArcs/SecondTypeIIbPieces.lean', 'w').write(header + "".join(out) + final)
print("ok", len(names))
