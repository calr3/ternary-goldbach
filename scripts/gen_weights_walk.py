# Data for Prelim/WeightsData*.lean and Prelim/WeightsMain.lean: the walk Wts.walkW over k <= 10^6,
# bounds for G(m) = sum_{2<=k<=m} |Lambda(k)-1|/k and H(m) = sum |Lambda(k)-1|/sqrt k at checkpoints
# (powers of 2 and floor(10^(s/16)), the points the cells of SchoenfeldCells.lean use).
import math, os, glob, re
S = 10**12
import sys
sys.argv = [sys.argv[0]]
_src = open('scripts/gen_e_walk.py').read()
exec(_src.split('"""', 2)[2].split("LOGS = {")[0].replace("os.path.dirname(os.path.abspath(__file__))", "'scripts'"))
G10LO, G10HI = 2302585092890, 2302585093112
LOGTAB = {int(L): tuple(v) for L, v in {"2": [693147180558, 693147180574], "3": [1098612288616, 1098612288727], "4": [1386294361068, 1386294361179], "5": [1609437912382, 1609437912496], "6": [1791759469175, 1791759469348], "7": [1945910149001, 1945910149563], "8": [2079441541576, 2079441541797], "9": [2197224577232, 2197224577454], "10": [2302585092890, 2302585093112]}.items()}
def nextLog(m, glo, ghi):
    if m + 1 <= 10: return LOGTAB[m + 1]
    return (glo + lgLo(m), ghi + lgHi(m))
def aT(m, lo, hi):
    l1, l2 = lamT(m, lo, hi)
    return (max(l1 - cdiv(S, m), 0) + max(S // m - l2, 0), max(max(l2 - S // m, 0), max(cdiv(S, m) - l1, 0)))
CK = sorted(set([2**s for s in range(1, 20)] + [int(math.floor(10**(s/16))) for s in range(19, 97)]))
CK = [c for c in CK if 2 <= c <= 1000000]
def main():
    st = (1, 0, 0, 0, 0, 0, 0)
    states = [st]; cur = st
    stops = set(CK)
    m = 1
    while m < 1000000:
        m_, glo, ghi, Glo, Ghi, Hlo, Hhi = cur
        steps = 0
        while True:
            g = nextLog(m, glo, ghi)
            assert 1 <= m and m + 1 <= 1000000 and g[0] >= 0
            a = aT(m + 1, g[0], g[1]); s = math.isqrt(m + 1)
            m, glo, ghi, Glo, Ghi, Hlo, Hhi = m + 1, g[0], g[1], Glo + a[0], Ghi + a[1], Hlo + a[0] * s, Hhi + a[1] * (s + 1)
            steps += 1
            if m in stops or steps >= 1100 or m == 1000000: break
        cur = (m, glo, ghi, Glo, Ghi, Hlo, Hhi)
        states.append(cur)
    print("chunks", len(states) - 1)
    for f in glob.glob("TernaryGoldbach/Prelim/WeightsData*.lean"): os.remove(f)
    PER = 100
    nchunks = len(states) - 1
    nfiles = (nchunks + PER - 1) // PER
    for fi in range(nfiles):
        i = fi + 1
        body = [f"""import TernaryGoldbach.Prelim.WeightsWalk

/-! Data for `Prelim/WeightsMain.lean` (generated by `scripts/gen_weights_walk.py`), part {i}. -/

namespace TernaryGoldbach.Prelim.Wts

set_option Elab.async false
"""]
        for k in range(fi * PER, min((fi + 1) * PER, nchunks)):
            a = states[k]; b = states[k + 1]; f = b[0] - a[0]
            body.append(f"""set_option maxRecDepth 100000 in
theorem chunkW{k} : resEqW (walkW {f} {a[0]} ({a[1]}) ({a[2]}) {a[3]} {a[4]} {a[5]} {a[6]}) {b[0]} ({b[1]}) ({b[2]}) {b[3]} {b[4]} {b[5]} {b[6]} = true := by
  decide +kernel
""")
        body.append("end TernaryGoldbach.Prelim.Wts\n")
        open(f"TernaryGoldbach/Prelim/WeightsData{i}.lean", "w").write("\n".join(body))
    M = ["\n".join(f"import TernaryGoldbach.Prelim.WeightsData{j}" for j in range(1, nfiles + 1)) + """

/-!
# `G` and `H` at the checkpoints (generated by `scripts/gen_weights_walk.py`)

`InvW m …` at every chunk end `m` of the walk `Wts.walkW`; `G_le`, `H_le`, `G_ge`, `H_ge` at the
checkpoints.
-/

namespace TernaryGoldbach.Prelim.Wts
"""]
    M.append("theorem stW0 : InvW 1 0 0 0 0 0 0 := invW_one\n")
    for k in range(nchunks):
        a = states[k]; b = states[k + 1]
        M.append(f"theorem stW{k+1} : InvW {b[0]} ({b[1]}) ({b[2]}) {b[3]} {b[4]} {b[5]} {b[6]} :=\n  walkW_spec _ _ _ _ _ _ _ _ _ _ _ _ _ _ _ stW{k} (resEqW_spec chunkW{k})\n")
    # checkpoint table
    tab = []
    for k, st in enumerate(states):
        if st[0] in set(CK): tab.append((st[0], st[3], st[4], st[5], st[6], k))
    M.append("/-- `(m, Glo, Ghi, Hlo, Hhi)` at the checkpoints. -/\ndef GHtab : List (ℕ × ℕ × ℕ × ℕ × ℕ) := [" +
             ", ".join(f"({m}, {a}, {b}, {c}, {d})" for m, a, b, c, d, k in tab) + "]\n")
    M.append("theorem GHtab_spec : ∀ e ∈ GHtab, (e.2.1 : ℝ) / S ≤ Gw e.1 ∧ Gw e.1 ≤ (e.2.2.1 : ℝ) / S ∧\n    (e.2.2.2.1 : ℝ) / S ≤ Hw e.1 ∧ Hw e.1 ≤ (e.2.2.2.2 : ℝ) / S := by\n  intro e he\n  simp only [GHtab, List.mem_cons, List.not_mem_nil, or_false] at he")
    M.append("  rcases he with " + " | ".join("rfl" for _ in tab))
    for (m, a, b, c, d, k) in tab:
        M.append(f"  · exact ⟨stW{k}.1, stW{k}.2.1, stW{k}.2.2.1, stW{k}.2.2.2.1⟩")
    M.append("\nend TernaryGoldbach.Prelim.Wts\n")
    open("TernaryGoldbach/Prelim/WeightsMain.lean", "w").write("\n".join(M))
    print("files", nfiles, "checkpoints", len(tab))
    import json
    json.dump(tab, open("/tmp/cde/ghtab.json", "w"))
if __name__ == "__main__":
    main()
