"""Generate the piecewise numerical proof of `a1_numeric` (SecondTypeIIaPieces.lean).

Every inequality handed to `norm_num` is first checked here in exact rational arithmetic.
"""
import os
from fractions import Fraction as F
from mpmath import mp, mpf, log, sqrt, e as E
mp.dps = 50

def Fd(x): return F(str(x))
def taylor6(f): return 1 + f + f**2/2 + f**3/6 + f**4/24 + f**5/120 + f**6/720
EM = Fd('2.7182818283')

def log_ub(z):
    """(n, f) with log z <= n + f, z <= EM^n taylor6(f), 0 <= f < 1, f with 4 decimals."""
    z = F(z)
    v = log(mpf(z.numerator) / z.denominator)
    n = int(v)
    f = F(int((v - n) * 10000) + 1, 10000)
    while not (z <= EM**n * taylor6(f)):
        f += F(1, 10000)
    if f >= 1:
        n += 1; f -= 1
        while not (z <= EM**n * taylor6(f)):
            f += F(1, 10000)
    assert z <= EM**n * taylor6(f)
    return n, f

def dec(x, places=4, up=True):
    q = F(10**places)
    import math
    v = x * q
    r = math.ceil(v) if up else math.floor(v)
    return F(r, 10**places)

def fstr(x):
    # exact decimal string for a Fraction with power-of-10 denominator
    s = str(float(x))
    assert Fd(s) == x, (x, s)
    return s

c = Fd('7.7583')
pts = ['15.6','16.4','17.3','18.3','19.5','21','23','25.5','29','34','41','52','70']
out = []
names = []
for i, (a, b) in enumerate(zip(pts, pts[1:])):
    A, B = Fd(a), Fd(b)
    n1, f1 = log_ub(B - Fd('1.7917')); u1 = n1 + f1
    n2, f2 = log_ub(B - Fd('6.0119')); u2 = n2 + f2
    n3, f3 = log_ub(2 * B); u3 = n3 + f3
    if A < Fd('15.83'):
        Bexact = Fd('0.15107') / (4 * c)
    else:
        Bexact = Fd('0.15107') * (A - c) / A**2
    Bb = dec(Bexact, 7)
    val = 12 * (Fd('1.7882') * u1 + Fd('0.9549')) * (1 - Fd('8.09') / B + (1 - Fd('1.0986') / B) * (u2 - Fd('0.732'))) * Bb
    m = F(int(sqrt(mpf(val.numerator) / val.denominator) * 10**5) + 1, 10**5)
    assert m * m >= val
    sa = F(int(sqrt(mpf(a)) * 10**5), 10**5)
    assert sa * sa <= A
    wv = Fd('0.24083') * (Fd('1.7882') * u3 + Fd('0.9549')) / 2
    w = F(int(sqrt(mpf(wv.numerator) / wv.denominator) * 10**5) + 1, 10**5)
    assert w * w >= wv
    ev = (4 * (Fd('0.49075') * (Fd('2.44949') / 4 * (Fd('1.01489') * Fd('2.0795') * (1 / A + Fd('0.49045') / A**2)) +
          Fd('0.007143') * (Fd('1.414214') * (1 - Fd('6.0119') / B)) + Fd('1.73207') * (1 / A + Fd('1.0373') / A**2) +
          Fd('0.028572') * Fd('1.414214') / A)) +
          8 * Fd('1.4262') * Fd('1.73207') * Fd('0.347013') / (A * sa) +
          4 * w * (Fd('0.057144') / (A * sa) + Fd('0.13418') * Fd('1.414214') / A))
    ee = F(int(ev * 10**5) + 1, 10**5)
    assert ee >= ev
    assert m + ee <= Fd('1.413'), (a, b, float(m + ee))
    if A < Fd('15.83'):
        hB = f"""(mul_le_mul_of_nonneg_left (div_sq_le_max (c := 7.7583) (by norm_num) (by linarith))
        (by norm_num)).trans (by norm_num)"""
    else:
        hB = f"""(mul_le_mul_of_nonneg_left (div_sq_anti (c := 7.7583) (by norm_num) (by norm_num)
        (by norm_num) haL) (by norm_num)).trans (by norm_num)"""
    name = f"a1_piece_{i}"
    names.append((a, b, name))
    out.append(f"""
theorem {name} {{L : ℝ}} (haL : ({a} : ℝ) ≤ L) (hLb : L ≤ {b}) :
    √(12 * a1F0 L * a1X0 L * a1B0 L) + a1SEC L ≤ 1.413 * (L * √L) := by
  have hm := a1M1_piece (a := {a}) (b := {b}) (u1 := {n1} + {fstr(f1)}) (u2 := {n2} + {fstr(f2)})
    (Bb := {fstr(Bb)}) (m := {fstr(m)}) (by norm_num) haL hLb
    (log_le_num {n1} {fstr(f1)} (by norm_num) (by norm_num) (by norm_num [taylor6]))
    (log_le_num {n2} {fstr(f2)} (by norm_num) (by norm_num) (by norm_num [taylor6]))
    ({hB}) (by norm_num) (by norm_num)
  have he := a1E_piece (a := {a}) (b := {b}) (sa := {fstr(sa)}) (u3 := {n3} + {fstr(f3)})
    (w := {fstr(w)}) (e := {fstr(ee)}) (by norm_num) haL hLb (by norm_num) (by norm_num)
    (log_le_num {n3} {fstr(f3)} (by norm_num) (by norm_num) (by norm_num [taylor6]))
    (by norm_num) (by norm_num) (by norm_num)
  have hs := a1SEC_le (show (15.6 : ℝ) ≤ L by linarith)
  have hLL : 0 ≤ L * √L := by positivity
  nlinarith [mul_le_mul_of_nonneg_right he hLL]
""")

header = '''import TernaryGoldbach.MinorArcs.SecondTypeIIaNum

/-!
# Case (a1): the pieces of `a1_numeric` (generated by `scripts/gen_a1_pieces.py`)
-/

open Real

namespace TernaryGoldbach.MinorArcs
'''
final = '''
theorem a1_piece_asym {L : ℝ} (hL : 70 ≤ L) :
    √(12 * a1F0 L * a1X0 L * a1B0 L) + a1SEC L ≤ 1.413 * (L * √L) := by
  have hm := a1M1_asym hL
  have he := a1E_asym hL
  have hs := a1SEC_le (show (15.6 : ℝ) ≤ L by linarith)
  have hLL : 0 ≤ L * √L := by positivity
  nlinarith [mul_le_mul_of_nonneg_right he hLL]

/-- **The numerical inequality of case (a1)**: `√(12 F₀X₀B₀) + SEC(L) ≤ 1.413 L^{3/2}`. -/
theorem a1_numeric {L : ℝ} (hL : 15.6 ≤ L) :
    √(12 * a1F0 L * a1X0 L * a1B0 L) + a1SEC L ≤ 1.413 * (L * √L) := by
'''
lines = []
for (a, b, name) in names:
    lines.append(f"  rcases le_or_gt L {b} with h{name} | h{name}\n  · exact {name} (by linarith) h{name}")
lines.append("  exact a1_piece_asym (by linarith)")
final += "\n".join(lines) + "\n\nend TernaryGoldbach.MinorArcs\n"
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'TernaryGoldbach/MinorArcs/SecondTypeIIaPieces.lean'), 'w').write(header + "".join(out) + final)
print("ok", len(names))
