# Data for Prelim/MuSieveData*.lean and Prelim/MuSieveMain.lean: the chain of packed mu-sieve windows
# (MuSieve.walkM) from n = 2 160 534 (where SmallMuMain ends) to N_END, checking |M(u)| <= 0.571 sqrt u.
# For each window (n, n + W]: W <= 4096 is the largest width for which both checks
# 10^6 (M + P)^2 <= 326041 n and 10^6 (M - N)^2 <= 326041 n hold (P, N = counts of mu = +1, -1 in the
# window, computed here with a numpy sieve; the kernel recomputes them), and t is the largest
# threshold with 2^(t + 26) <= (n + 1)^4.
import math, sys, os, glob
import numpy as np

N0 = 2160534
N_END = 100_000_000
WMAX = 4096
CHUNK = 200        # windows per chunk
PER_FILE = 4       # chunks per file
LANES = 6          # independent import chains

def mobius(N):
    mu = np.ones(N + 1, dtype=np.int8); mu[0] = 0
    pr = np.ones(N + 1, dtype=np.int64)
    r = math.isqrt(N) + 1
    s = np.ones(r + 1, dtype=bool); s[:2] = False
    for p in range(2, math.isqrt(r) + 1):
        if s[p]: s[p * p::p] = False
    for p in np.nonzero(s)[0]:
        p = int(p); mu[::p] *= -1; pr[::p] *= p; mu[::p * p] = 0
    big = (pr != np.arange(N + 1, dtype=np.int64)) & (mu != 0)
    mu[big] *= -1
    return mu

def chk(x, n): return 10**6 * x * x <= 326041 * n

def main():
    N = N_END + WMAX + 10
    mu = mobius(N)
    posC = np.concatenate([[0], np.cumsum(mu == 1, dtype=np.int64)])   # posC[k] = #{1<=j<k : mu=1}... index shift below
    negC = np.concatenate([[0], np.cumsum(mu == -1, dtype=np.int64)])
    M = np.cumsum(mu, dtype=np.int64)
    def P(n, W): return int(posC[n + W + 1] - posC[n + 1])
    def Nn(n, W): return int(negC[n + W + 1] - negC[n + 1])
    n = N0; Mv = int(M[N0])
    wins = []; states = [(n, Mv)]
    while n < N_END:
        lo, hi = 1, WMAX
        def ok(W): return chk(Mv + P(n, W), n) and chk(Mv - Nn(n, W), n)
        assert ok(1), (n, Mv)
        if not ok(hi):
            while hi - lo > 1:
                mid = (lo + hi) // 2
                if ok(mid): lo = mid
                else: hi = mid
            W = lo
        else:
            W = hi
        t = ((n + 1) ** 4).bit_length() - 1 - 26
        assert 2 ** (t + 26) <= (n + 1) ** 4 and (n + W) ** 4 < 2 ** t * 10007 ** 4 and t <= 128
        assert n + W < 10007 ** 2
        Mv = Mv + P(n, W) - Nn(n, W)
        n += W
        assert Mv == int(M[n])
        wins.append((W, t)); states.append((n, Mv))
    print("windows", len(wins), "end", n, Mv, file=sys.stderr)
    chunks = []
    for c0 in range(0, len(wins), CHUNK):
        ws = wins[c0:c0 + CHUNK]
        chunks.append((states[c0], ws, states[c0 + len(ws)]))
    for f in glob.glob("TernaryGoldbach/Prelim/MuSieveData*.lean"): os.remove(f)
    nfiles = (len(chunks) + PER_FILE - 1) // PER_FILE
    for fi in range(nfiles):
        i = fi + 1
        imp = "TernaryGoldbach.Prelim.MuSieve" if i <= LANES else f"TernaryGoldbach.Prelim.MuSieveData{i - LANES}"
        body = [f"""import {imp}

/-! Data for `Prelim/MuSieveMain.lean` (generated by `scripts/gen_mu_sieve.py`), part {i}. -/

namespace TernaryGoldbach.Prelim.MuSieve

set_option Elab.async false
"""]
        for k in range(fi * PER_FILE, min((fi + 1) * PER_FILE, len(chunks))):
            (a, Ma), ws, (b, Mb) = chunks[k]
            wl = "[" + ", ".join(f"({W}, {t})" for W, t in ws) + "]"
            body.append(f"""set_option maxRecDepth 100000 in
def ws{k} : List (ℕ × ℕ) := {wl}

set_option maxRecDepth 100000 in
theorem chunk{k} : resEqM (walkM ws{k} {a} ({Ma})) {b} ({Mb}) = true := by
  decide +kernel
""")
        body.append("end TernaryGoldbach.Prelim.MuSieve\n")
        open(f"TernaryGoldbach/Prelim/MuSieveData{i}.lean", "w").write("\n".join(body))
    last = list(range(max(1, nfiles - LANES + 1), nfiles + 1))
    Mm = ["\n".join(f"import TernaryGoldbach.Prelim.MuSieveData{j}" for j in last) + """
import TernaryGoldbach.Prelim.SmallMuMain

/-!
# `|M(u)| ≤ 0.571 √u` for `100 ≤ u ≤ 10⁸`

The chain of packed `μ`-sieve windows (`MuSieve.walkM`, data `Prelim/MuSieveData*.lean`, generated by
`scripts/gen_mu_sieve.py`) from `2 160 534`, where the trial-division walk (`SmallMuMain`) ends.
-/

open Finset
open scoped ArithmeticFunction.Moebius

namespace TernaryGoldbach.Prelim.MuSieve
"""]
    (a0, M0) = states[0]
    Mm.append(f"""theorem Mz_start : Mz {a0} = {M0} := by
  have h := SmallMu.sum_mu_eq {a0}
  obtain ⟨hs, -⟩ := SmallMu.u1080
  simp only [Prod.mk.injEq] at hs
  rw [hs.1, hs.2.1] at h
  have : (Mz {a0} : ℝ) = ∑ n ∈ Icc 1 {a0}, (μ n : ℝ) := by unfold Mz; push_cast; rfl
  have h' : ((Mz {a0} : ℤ) : ℝ) = (({M0} : ℤ) : ℝ) := by rw [this, h]; norm_num
  exact_mod_cast h'
""")
    for k, ((a, Ma), ws, (b, Mb)) in enumerate(chunks):
        stmt = f"Mz {b} = {Mb} ∧ ∀ u, {a0} < u → u ≤ {b} → 10 ^ 6 * (Mz u * Mz u) ≤ 326041 * (u : ℤ)"
        if k == 0:
            Mm.append(f"""theorem stg0 : {stmt} := by
  obtain ⟨h1, -, h3⟩ := walkM_spec ws0 {a} ({Ma}) {b} ({Mb}) Mz_start (resEqM_spec chunk0)
  exact ⟨h1, h3⟩
""")
        else:
            Mm.append(f"""theorem stg{k} : {stmt} := by
  obtain ⟨p1, p3⟩ := stg{k - 1}
  obtain ⟨h1, -, h3⟩ := walkM_spec ws{k} {a} ({Ma}) {b} ({Mb}) p1 (resEqM_spec chunk{k})
  refine ⟨h1, fun u hu1 hu2 => ?_⟩
  rcases le_or_gt u {a} with h | h
  · exact p3 u hu1 h
  · exact h3 u h hu2
""")
    K = len(chunks) - 1
    end = chunks[-1][2][0]
    Mm.append(f"""/-- `10⁶ M(u)² ≤ 326041 u` for `2 160 534 < u ≤ {end}`. -/
theorem M_sieve {{u : ℕ}} (h1 : {a0} < u) (h2 : u ≤ {end}) : 10 ^ 6 * (Mz u * Mz u) ≤ 326041 * (u : ℤ) :=
  (stg{K}).2 u h1 h2

end TernaryGoldbach.Prelim.MuSieve
""")
    open("TernaryGoldbach/Prelim/MuSieveMain.lean", "w").write("\n".join(Mm))
    print("chunks", len(chunks), "files", nfiles, file=sys.stderr)

if __name__ == "__main__":
    main()
