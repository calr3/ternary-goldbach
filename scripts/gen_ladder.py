#!/usr/bin/env python3
"""Generate the data files of the prime ladder (`TernaryGoldbach/Ladder/Data/L*.lean`, `Data.lean`).

The ladder has one rung for each `1 <= i <= IMAX`, checked in chunks of 4096 rungs
(`TernaryGoldbach.Ladder.ChunkOK`). File `Lkkk.lean` is one `ladder_chunks a n` command, which proves
`RunsOK a n`; `Data.lean` combines the files into `RunsOK 1 NCHUNKS`. The files contain no data:
`ladder_hints%` (`LadderHints.lean`) computes the hints during elaboration.

Usage: python3 scripts/gen_ladder.py
"""

from pathlib import Path

S = 111616
F = 2 ** 45
IMAX = (10 ** 27 - 5) // (S * F)  # the largest rung needed for n <= 10^27
CHUNK = 4096
NCHUNKS = -(-IMAX // CHUNK)
NFILES = 128

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "TernaryGoldbach" / "Ladder" / "Data"


def tree(leaves):
    """A balanced `RunsOK.append` term over `leaves = [(a, n, term)]`; returns `(a, n, term)`."""
    if len(leaves) == 1:
        return leaves[0]
    mid = len(leaves) // 2
    a, m, left = tree(leaves[:mid])
    b, n, right = tree(leaves[mid:])
    term = (f"(RunsOK.append (a := {a}) (b := {b}) (c := {m + n}) (m := {m}) (n := {n})\n"
            f"    {left}\n    {right} rfl rfl)")
    return a, m + n, term


def main():
    assert IMAX == 254638308
    assert 1 + CHUNK * NCHUNKS <= 2 ** 28 and S * (1 + CHUNK * NCHUNKS) <= F
    DATA.mkdir(parents=True, exist_ok=True)
    base, extra = divmod(NCHUNKS, NFILES)
    files = []
    c = 0
    for k in range(NFILES):
        cnt = base + (1 if k < extra else 0)
        files.append(list(range(c, c + cnt)))
        c += cnt
    assert c == NCHUNKS
    parts = []
    for k, chunks in enumerate(files):
        name = f"L{k:03d}"
        a0 = 1 + CHUNK * chunks[0]
        lines = [
            "import TernaryGoldbach.Ladder.Check",
            "import LadderHints",
            "",
            "/-!",
            f"# Prime ladder, rungs `[{a0}, {a0 + CHUNK * len(chunks)})`",
            "",
            "Generated by `scripts/gen_ladder.py`. `ladder_chunks` (`LadderHints.lean`) declares one",
            "theorem `ChunkOK` per chunk of 4096 rungs, checked by the kernel (`decide +kernel`) from hints",
            "computed during elaboration (`ladder_hints%`), and `all : RunsOK` for the file.",
            "-/",
            "",
            f"namespace TernaryGoldbach.Ladder.{name}",
            "",
            "open TernaryGoldbach.Ladder",
            "",
            "-- one theorem at a time: parallel elaboration of 486 chunks needs about 7 GB",
            "set_option Elab.async false",
            "",
        ]
        lines += [f"ladder_chunks {a0} {len(chunks)}", "",
                  f"end TernaryGoldbach.Ladder.{name}", ""]
        (DATA / f"{name}.lean").write_text("\n".join(lines))
        parts.append((a0, len(chunks), f"{name}.all"))
    imports = "\n".join(f"import TernaryGoldbach.Ladder.Data.L{k:03d}" for k in range(NFILES))
    a, n, term = tree(parts)
    text = f"""{imports}

/-!
# Prime ladder: all chunks

Generated by `scripts/gen_ladder.py`. The rungs `1 ≤ i < {a + CHUNK * n}` pass the kernel check.
-/

namespace TernaryGoldbach.Ladder

theorem runsOK_all : RunsOK {a} {n} :=
  {term}

end TernaryGoldbach.Ladder
"""
    (DATA.parent / "Data.lean").write_text(text)
    print(f"IMAX = {IMAX}, {NCHUNKS} chunks in {NFILES} files, rungs 1 ≤ i < {1 + CHUNK * NCHUNKS}")


if __name__ == "__main__":
    main()
