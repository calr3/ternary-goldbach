"""Generate the kernel checks of `Prelim/SmallMcheck.lean`: `|m̌(k)| ≤ 1.00303` for `1 ≤ k ≤ 2·10⁵`
and `∑_{t < 2·10⁵} |M(t)|/t ≤ 131`.

The walk mirrors `SmallMcheck.step` exactly, in Python integers (Lean's `/` on `ℤ` with a positive
divisor is floor division, as is Python's `//`). The states every `CHUNK` steps are written to
`TernaryGoldbach/Prelim/SmallMcheckData*.lean` as `walk CHUNK sᵢ = some sᵢ₊₁` (checked by the kernel)
and chained in `SmallMcheckMain.lean`.

Usage: python3 scripts/gen_mcheck_small.py [--write]
"""
import os, sys

B = 10 ** 20
CB = 100303 * 10 ** 15          # 1.00303 B
KMAX = 200000
CHUNK = 2000
PER_FILE = 10                   # chunks per data file
SBOUND = 131 * B                # the bound on B ∑ |M(t)|/t


def mu_table(n):
    mu = [1] * (n + 1)
    mu[0] = 0
    isp = bytearray([1]) * (n + 1)
    isp[0] = isp[1] = 0
    for p in range(2, n + 1):
        if isp[p]:
            for k in range(2 * p, n + 1, p):
                isp[k] = 0
            for k in range(p, n + 1, p):
                mu[k] = -mu[k]
            for k in range(p * p, n + 1, p * p):
                mu[k] = 0
    return mu


def nT(k):
    return 32 if k < 64 else (6 if k < 4096 else 3)


def p_sum(k, n):
    return sum((-1) ** i * (B // ((i + 1) * k ** (i + 1))) for i in range(n))


def err_b(k, n):
    return B // (k ** n * (k - 1)) + 1


def log_lo(k):
    if k == 1:
        return 69314718030000000000
    n = nT(k)
    return p_sum(k, n) - n - err_b(k, n)


def log_hi(k):
    if k == 1:
        return 69314718080000000000
    n = nT(k)
    return p_sum(k, n) + n + err_b(k, n)


def step(s, mu):
    k, M, mlo, mhi, clo, chi, shi = s
    lo, hi = log_lo(k), log_hi(k)
    ps = (mlo * lo, mlo * hi, mhi * lo, mhi * hi)
    clo2 = clo + min(ps) // B
    chi2 = chi + -((-max(ps)) // B)
    shi2 = shi + (abs(M) * B + k - 1) // k
    v = mu[k + 1]
    if not (-CB <= clo2 and chi2 <= CB):
        raise SystemExit(f"check fails at k + 1 = {k + 1}: [{clo2}, {chi2}]")
    return (k + 1, M + v, mlo + (v * B) // (k + 1), mhi + -((-(v * B)) // (k + 1)), clo2, chi2, shi2)


def lean_state(s):
    k, M, mlo, mhi, clo, chi, shi = s
    i = lambda z: f"({z})" if z < 0 else str(z)
    return f"⟨{k}, {i(M)}, {i(mlo)}, {i(mhi)}, {i(clo)}, {i(chi)}, {shi}⟩"


def main():
    mu = mu_table(KMAX + 1)
    s = (1, 1, B, B, 0, 0, 0)
    states = [s]
    worst = (0, 0)
    while s[0] < KMAX:
        s = step(s, mu)
        margin = CB - max(s[5], -s[4])
        if worst[1] == 0 or margin < worst[1]:
            worst = (s[0], margin)
        if (s[0] - 1) % CHUNK == 0 or s[0] == KMAX:
            states.append(s)
    print(f"final k = {s[0]}, B·∑|M|/t ≤ {s[6] / B:.4f} (bound 131), smallest margin {worst[1] / B:.3e} at k = {worst[0]}")
    assert s[6] <= SBOUND
    print(f"{len(states) - 1} chunks")
    if "--write" in sys.argv:
        write(states)


def write(states):
    root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "TernaryGoldbach", "Prelim")
    chunks = list(zip(states, states[1:]))
    files = [chunks[i:i + PER_FILE] for i in range(0, len(chunks), PER_FILE)]
    for fi, group in enumerate(files):
        lines = ["import TernaryGoldbach.Prelim.SmallMcheck", "",
                 "/-! Generated by `scripts/gen_mcheck_small.py`: chunks of the walk of `SmallMcheck.lean`. -/", "",
                 "namespace TernaryGoldbach.Prelim.SmallMcheck", ""]
        for ci, (a, b) in enumerate(group):
            n = b[0] - a[0]
            idx = fi * PER_FILE + ci
            lines.append(f"theorem chunk_{idx} : walk {n} {lean_state(a)} =")
            lines.append(f"    some {lean_state(b)} := by")
            lines.append("  decide +kernel")
            lines.append("")
        lines.append("end TernaryGoldbach.Prelim.SmallMcheck")
        with open(os.path.join(root, f"SmallMcheckData{fi + 1}.lean"), "w") as f:
            f.write("\n".join(lines) + "\n")
    # the chain
    imp = [f"import TernaryGoldbach.Prelim.SmallMcheckData{fi + 1}" for fi in range(len(files))]
    body = ["", "/-! Generated by `scripts/gen_mcheck_small.py`: the chunks of `SmallMcheckData*.lean`, chained. -/",
            "", "namespace TernaryGoldbach.Prelim.SmallMcheck", "",
            f"theorem walk_all : Good {lean_state(states[-1])} ∧",
            f"    ∀ j : ℕ, 1 ≤ j → j ≤ {states[-1][0]} → |mcheck (j : ℝ)| ≤ 1.00303 := by",
            "  have h0 := good_init"]
    for idx in range(len(chunks)):
        body.append(f"  have h{idx + 1} := chain h{idx}.1 h{idx}.2 chunk_{idx}")
    body.append(f"  exact h{len(chunks)}")
    body.append("")
    body.append("end TernaryGoldbach.Prelim.SmallMcheck")
    with open(os.path.join(root, "SmallMcheckMain.lean"), "w") as f:
        f.write("\n".join(imp + body) + "\n")
    print(f"wrote {len(files)} data files and SmallMcheckMain.lean")


if __name__ == "__main__":
    main()
