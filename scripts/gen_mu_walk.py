"""Data for Prelim/SmallMuData*.lean and Prelim/SmallMuMain.lean: the kernel walk of mu up to 2 160 534
(Prelim/SmallMuWalk.lean). Chunks of at most 2000 integers; in [11815, 10^6] each chunk carries a
certified L with log(b + 1) < L/10^12 (b the chunk end), and the check (|P - Q| + n) L <= 3·10^25
is simulated exactly.

Usage: python3 scripts/gen_mu_walk.py"""
import math, sys, os, glob
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import io, contextlib
from fractions import Fraction as Q
import numpy as np
with contextlib.redirect_stdout(io.StringIO()):
    from cert_tables import ELpow, T12
SL = 10**12
D = 10**15
TOP = 2160534
def chkStep(cN, cD, n, L):
    a = cN*n//cD; r = cN*n % cD
    return Q(L) < ELpow(a)*T12(Q(r, cD))
def loghi(e):
    hi = math.ceil(SL*math.log(e)) + 2
    while not chkStep(hi, SL, 1, e): hi += 1
    return hi
N = TOP + 10
mu = np.ones(N + 1, dtype=np.int64); mu[0] = 0
isp = np.ones(N + 1, bool); isp[:2] = False
for p in range(2, N + 1):
    if isp[p]:
        isp[2*p::p] = False; mu[p::p] *= -1; mu[p*p::p*p] = 0
# exact running states
states = {}
Mp = Mn = P = Qv = 0
Ps = [0]*(N+1); Qs = [0]*(N+1); Mps = [0]*(N+1); Mns = [0]*(N+1)
for k in range(1, N + 1):
    if mu[k] == 1: Mp += 1; P += D//k
    elif mu[k] == -1: Mn += 1; Qv += D//k
    Mps[k], Mns[k], Ps[k], Qs[k] = Mp, Mn, P, Qv
    if k >= 100: assert (Mp - Mn)**2*10**8 <= 32171584*k, k
def mok(a, b, L):
    for k in range(max(a + 1, 11815), min(b, TOP) + 1):
        if (abs(Ps[k] - Qs[k]) + k)*L > 3*10**25: return False
    return True
# chunk boundaries: forced at 11814 and 10^6
chunks = []
a = 0
forced = [11814, TOP]
while a < TOP:
    nxt = min(f for f in forced if f > a)
    b = min(a + 2000, nxt)
    inm = not (b < 11815 or a + 1 > TOP)
    if inm:
        while True:
            L = loghi(b + 1)
            if mok(a, b, L): break
            b = a + max(1, (b - a)//2)
    else:
        L = 0
    chunks.append((a, b, L, inm))
    a = b
print("chunks", len(chunks))
def st(k): return (Mps[k], Mns[k], Ps[k], Qs[k])
for f in glob.glob("TernaryGoldbach/Prelim/SmallMuData*.lean"): os.remove(f)
per_file = 100
files = []
HDR = """import {imp}

/-! Data for `Prelim/SmallMuWalk.lean` (generated by `scripts/gen_mu_walk.py`), part {i}: the walk on
`({a}, {b}]`. -/

namespace TernaryGoldbach.Prelim.SmallMu

set_option Elab.async false
"""
for f0 in range(0, len(chunks), per_file):
    i = f0//per_file + 1
    imp = "TernaryGoldbach.Prelim.SmallMuWalk" if i == 1 else f"TernaryGoldbach.Prelim.SmallMuData{i-1}"
    body = [HDR.format(imp=imp, i=i, a=chunks[f0][0], b=chunks[min(f0 + per_file, len(chunks)) - 1][1])]
    for j in range(f0, min(f0 + per_file, len(chunks))):
        a, b, L, inm = chunks[j]
        s0, s1 = st(a), st(b)
        prev = "upto_zero" if j == 0 else f"u{j-1}"
        body.append(f"set_option maxRecDepth 100000 in\ntheorem w{j} : walk {L} {a} {' '.join(map(str, s0))} {b-a} = some ({', '.join(map(str, s1))}) := by\n  decide +kernel\n")
        if inm:
            body.append(f"theorem c{j} : Small.chkStep {L} 1000000000000 1 ({a} + {b-a} + 1) = true := by decide +kernel\n")
            hl = f"Or.inr (log_lt_of_cert (by norm_num) c{j})"
        else:
            hl = "Or.inl (fun k h1 h2 => by omega)"
        body.append(f"theorem u{j} : Upto {b} {' '.join(map(str, s1))} :=\n  upto_step (a := {a}) (len := {b-a}) {prev} (by norm_num) w{j} ({hl})\n")
    body.append("end TernaryGoldbach.Prelim.SmallMu\n")
    open(f"TernaryGoldbach/Prelim/SmallMuData{i}.lean", "w").write("\n".join(body))
    files.append(i)
K = len(chunks) - 1
assert chunks[-1][1] == TOP
main = f"""import TernaryGoldbach.Prelim.SmallMuData{files[-1]}

/-!
# `|M(n)| ≤ 0.5672 √n` on `[100, 2 160 534]` and `|m(n)| log(n + 1) ≤ 0.03` on `[11815, 2 160 534]`

From the kernel walk of `Prelim/SmallMuWalk.lean` (data `Prelim/SmallMuData*.lean`, generated by
`scripts/gen_mu_walk.py`).
-/

open Finset ArithmeticFunction
open scoped ArithmeticFunction.Moebius

namespace TernaryGoldbach.Prelim.SmallMu

theorem good_all {{k : ℕ}} (h1 : 1 ≤ k) (h2 : k ≤ {TOP}) : Good k := (u{K}).2 k h1 h2

/-- **`|M(n)| ≤ 0.5672 √n`** for `100 ≤ n ≤ 2 160 534`. -/
theorem M_small {{n : ℕ}} (h1 : 100 ≤ n) (h2 : n ≤ {TOP}) :
    |∑ k ∈ Icc 1 n, (μ k : ℝ)| ≤ 0.5672 * √(n : ℝ) :=
  M_bound_of_good h1 (good_all (by omega) h2)

/-- **`|m(k)| log(k + 1) ≤ 0.03`** for `11815 ≤ k ≤ 2 160 534`. -/
theorem m_small {{k : ℕ}} (h1 : 11815 ≤ k) (h2 : k ≤ {TOP}) :
    |∑ n ∈ Icc 1 k, (μ n : ℝ) / n| * Real.log ((k : ℝ) + 1) ≤ 0.03 :=
  m_bound_of_good h1 h2 (good_all (by omega) h2)

end TernaryGoldbach.Prelim.SmallMu
"""
open("TernaryGoldbach/Prelim/SmallMuMain.lean", "w").write(main)
print("files", len(files))
